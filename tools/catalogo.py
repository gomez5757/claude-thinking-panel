"""Builds catalogo/, the edition of the plugin submitted to Anthropic's directory, from the full plugin.

The directory's policy does not allow reading chat history or calling endpoints the author does not own, so the
edition leaves out the usage web page, the limits log and Edge's translator. In the sources, code between
//#if full and //#else (or //#endif) is dropped, and lines between //#else and //#endif written as //: <code>
are uncommented. catalogo/.claude-plugin/plugin.json and catalogo/README.md are written by hand.

Run it after changing the plugin: python -I tools/catalogo.py. With --check it only says whether catalogo/ is current.
"""
import os, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'catalogo')
FILTERED = ['hooks/register.tsx']
# The tests stay out of catalogo/: inside the full plugin's folder they would run against the full plugin too.
# python -I tools/catalogo.py --with-tests <folder> writes the edition with its tests there, for claude plugin test.
TESTS = ['hooks/panel.test.tsx', 'hooks/translator.test.tsx']
HAND = ['.claude-plugin/plugin.json', '.claude-plugin/icon.png', 'README.md']
COPIED = ['hooks/hooks.json', 'types/index.d.ts', 'LICENSE', 'tsconfig.json']
HEADER = '// Generated by tools/catalogo.py from the full plugin\'s {0}: edit that file and run the script again.\n'


def edition(text, path):
    out, mode = [], None
    for line in text.replace('\r\n', '\n').split('\n'):
        mark = line.strip()
        if mark == '//#if full':
            if mode is not None:
                raise SystemExit(f'{path}: nested //#if full')
            mode = 'full'
        elif mark in ('//#else', '//#endif'):
            if mode is None:
                raise SystemExit(f'{path}: {mark} without //#if full')
            mode = 'else' if mark == '//#else' else None
        elif mode == 'else':
            body = line.lstrip()
            out.append(line[:len(line) - len(body)] + body[4:] if body.startswith('//: ') else line)
        elif mode is None:
            out.append(line)
    if mode is not None:
        raise SystemExit(f'{path}: //#if full without //#endif')
    return HEADER.format(path) + '\n'.join(out)


def files(tests=False):
    for rel in FILTERED + (TESTS if tests else []):
        with open(os.path.join(ROOT, rel), encoding='utf-8', newline='') as f:
            yield rel, edition(f.read(), rel).encode('utf-8')
    for rel in COPIED:
        with open(os.path.join(ROOT, rel), 'rb') as f:
            yield rel, f.read()


def main():
    check = '--check' in sys.argv
    if '--with-tests' in sys.argv:
        out = os.path.abspath(sys.argv[sys.argv.index('--with-tests') + 1])
        for rel, data in list(files(tests=True)) + [(r, open(os.path.join(OUT, r), 'rb').read()) for r in HAND]:
            os.makedirs(os.path.dirname(os.path.join(out, rel)), exist_ok=True)
            with open(os.path.join(out, rel), 'wb') as f:
                f.write(data)
        print(f'edition with tests written to {out}')
        return
    stale = []
    for rel, data in files():
        dest = os.path.join(OUT, rel)
        old = open(dest, 'rb').read() if os.path.exists(dest) else None
        # Git may turn line ends into CRLF on checkout: that alone is not a change.
        if old is not None and old.replace(b'\r\n', b'\n') == data.replace(b'\r\n', b'\n'):
            continue
        stale.append(rel)
        if not check:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, 'wb') as f:
                f.write(data)
    if check:
        print('catalogo/ is current' if not stale else 'catalogo/ is out of date: ' + ', '.join(stale))
        sys.exit(1 if stale else 0)
    print('catalogo/ updated: ' + (', '.join(stale) or 'nothing changed'))


if __name__ == '__main__':
    main()
